import struct
import tarfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('package_delta_fixture', ROOT / 'scripts/install-test-access-packages.py')
packages = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(packages)

# Debian's reviewed maintainer script is fixture data only; never executed.
POSTINST = b'#!/bin/sh\n\nset -e\n\ncase "$1" in\n    configure)\n        # Add the i2c group unless it\'s already there\n        if ! getent group i2c >/dev/null; then\n                addgroup --quiet --system i2c || true\n        fi\n\n        # Trigger a udev reload\n        if which udevadm >/dev/null 2>&1 ; then\n                udevadm control --reload-rules || true\n                udevadm trigger --subsystem-match=i2c-dev --action=change || true\n        fi\n    ;;\n\n    abort-upgrade|abort-remove|abort-deconfigure)\n    ;;\n\n    *)\n        echo "postinst called with unknown argument \\`$1\'" >&2\n        exit 1\n    ;;\nesac\n\n# dh_installdeb will replace this with shell code automatically\n# generated by other debhelper scripts.\n\n\n\nexit 0\n'
TRIGGERS = b'# Triggers added by dh_makeshlibs/13.24.2\nactivate-noawait ldconfig\n'


def _encoded(value):
    return (json.dumps(value, sort_keys=True, separators=(',', ':')) + '\n').encode()


def _directory():
    return {'type': 'directory', 'mode': '0755', 'uid': 0, 'gid': 0,
            'xattrs': {'status': 'inspected', 'entries': {}}}


def _tar(entries):
    """Entries are (kind, bytes-or-link-target, mode); produce deterministic XZ/USTAR."""
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode='w:xz', format=tarfile.USTAR_FORMAT) as archive:
        for name, (kind, content, mode) in sorted(entries.items()):
            entry = tarfile.TarInfo(name)
            entry.mode, entry.uid, entry.gid, entry.mtime = mode, 0, 0, 0
            if kind == 'directory':
                entry.type = tarfile.DIRTYPE
            elif kind == 'symlink':
                entry.type, entry.linkname = tarfile.SYMTYPE, content
            else:
                entry.size = len(content)
            archive.addfile(entry, io.BytesIO(content) if kind == 'file' else None)
    return output.getvalue()


def _ar(entries):
    output = bytearray(b'!<arch>\n')
    for name, raw in entries:
        header = f'{name + "/":<16}{0:<12}{0:<6}{0:<6}{"100644":<8}{len(raw):<10}`\n'.encode('ascii')
        assert len(header) == 60
        output.extend(header + raw + (b'\n' if len(raw) % 2 else b''))
    return bytes(output)


def _status(rows):
    return ('\n\n'.join('\n'.join(f'{key}: {value}' for key, value in row.items())
                        for row in rows) + '\n\n').encode()


def synthetic_cache(entries):
    """Small real glibc1.1 LE cache with absolute string offsets and no extensions."""
    start = 48 + len(entries) * 24
    strings, records = bytearray(), bytearray()
    for flags, name, path in entries:
        key = start + len(strings)
        strings.extend(name.encode() + b'\0')
        value = start + len(strings)
        strings.extend(path.encode() + b'\0')
        records.extend(struct.pack('<iIIIQ', flags, key, value, 0, 0))
    header = bytearray(48)
    header[:20] = b'glibc-ld.so.cache1.1'
    struct.pack_into('<II', header, 20, len(entries), len(strings))
    header[28] = 2
    return bytes(header + records + strings)


def synthetic_package_fixture(parent_root=None):
    """Return independent {blobs,before,after,state_before,state_after,report} copies.

    The optional parent inventory is copied. Its dpkg/cache entries are replaced
    with synthetic dependencies, so callers must use returned before as parent.
    Nothing in cache/packages or on the host is inspected or installed.
    """
    lock = json.loads((ROOT / packages.LOCK).read_bytes())
    blobs, rows, payloads, controls = {}, {}, {}, {}
    for package in lock['packages']:
        name = package['name']
        fields = {'Package': name, 'Version': package['version'], 'Architecture': 'arm64',
                  'Depends': package['depends'], 'Description': 'Inert synthetic package fixture'}
        if name == 'libi2c0':
            fields['Multi-Arch'] = 'same'
        rows[name] = fields
        payload = {'usr/share/doc/' + name + '/' + leaf: ('file', ('fixture ' + leaf + '\n').encode(), 0o644)
                   for leaf in ('changelog.Debian.gz', 'changelog.gz', 'copyright')}
        if name == 'libi2c0':
            payload.update({'usr/lib/aarch64-linux-gnu/libi2c.so.0': ('symlink', 'libi2c.so.0.1.1', 0o777),
                            'usr/lib/aarch64-linux-gnu/libi2c.so.0.1.1': ('file', b'synthetic library\n', 0o644)})
        else:
            for prefix, names in [('usr/bin/', ('ddcmon', 'decode-dimms', 'decode-edid', 'decode-vaio')),
                    ('usr/sbin/', ('i2c-stub-from-dump', 'i2cdetect', 'i2cdump', 'i2cget', 'i2cset', 'i2ctransfer'))]:
                payload.update({prefix + leaf: ('file', b'#!/bin/sh\nexit 99\n', 0o755) for leaf in names})
            payload['usr/lib/udev/rules.d/60-i2c-tools.rules'] = ('file', b'# inert fixture\n', 0o644)
            for section, names in [('1', ('decode-dimms', 'decode-vaio')), ('3', ('libi2c',)),
                    ('8', ('i2c-stub-from-dump', 'i2cdetect', 'i2cdump', 'i2cget', 'i2cset', 'i2ctransfer'))]:
                payload.update({'usr/share/man/man' + section + '/' + leaf + '.' + section + '.gz':
                                ('file', b'inert manual\n', 0o644) for leaf in names})
        for path in list(payload):
            for ancestor in PurePosixPath(path).parents:
                payload.setdefault(str(ancestor), ('directory', None, 0o755))
        md5 = ''.join(hashlib.md5(data, usedforsecurity=False).hexdigest() + '  ' + path + '\n'
                      for path, (kind, data, _mode) in sorted(payload.items()) if kind == 'file').encode()
        control = {'.': ('directory', None, 0o755), 'control': ('file', _status([fields]), 0o644),
                   'md5sums': ('file', md5, 0o644)}
        if name == 'libi2c0':
            control.update({'shlibs': ('file', b'libi2c 0 libi2c0 (>= 4.0)\n', 0o644),
                            'symbols': ('file', b'libi2c.so.0 libi2c0 #MINVER#\n', 0o644),
                            'triggers': ('file', TRIGGERS, 0o644)})
        else:
            control['postinst'] = ('file', POSTINST, 0o755)
        raw = _ar([('debian-binary', b'2.0\n'), ('control.tar.xz', _tar(control)), ('data.tar.xz', _tar(payload))])
        package.update(sha256=hashlib.sha256(raw).hexdigest(), size_bytes=len(raw))
        blobs['packages/' + package['filename']] = raw
        payloads[name], controls[name] = payload, control
    blobs[packages.LOCK] = _encoded(lock)
    before = copy.deepcopy(parent_root or {})
    before.setdefault('.', _directory())
    for payload in payloads.values():
        for path, (kind, _raw, _mode) in payload.items():
            if kind == 'directory':
                before.setdefault(path, _directory())
    for name in ('var', 'var/lib', 'var/lib/dpkg', 'var/lib/dpkg/info', 'etc'):
        before.setdefault(name, _directory())
    dependencies = {}
    for package in lock['packages']:
        for row in package['required_dependencies_in_base']:
            dependencies[(row['name'], row['architecture'])] = {'Package': row['name'], 'Architecture': row['architecture'],
                'Version': row['version'], 'Status': 'install ok installed'}
    base_rows = list(dependencies.values())
    base_cache = [(0xa03, 'libc.so.6', '/lib/aarch64-linux-gnu/libc.so.6')]
    state_before = {packages.STATUS: _status(base_rows), packages.CACHE: synthetic_cache(base_cache)}
    before.update({path: packages.file_record(raw) for path, raw in state_before.items()})
    after = copy.deepcopy(before)
    state_after = {packages.STATUS: _status(base_rows + [dict(row, Status='install ok installed') for row in rows.values()]),
                   packages.CACHE: synthetic_cache(base_cache + [(0xa03, 'libi2c.so.0', '/lib/aarch64-linux-gnu/libi2c.so.0')])}
    for package, control, payload, fields in packages.reviewed_packages(blobs):
        for path, (record, _raw) in payload.items():
            after.setdefault(path, record)
        prefix = 'var/lib/dpkg/info/' + package['name'] + (':arm64' if fields.get('Multi-Arch') == 'same' else '')
        for leaf, (record, _raw) in control.items():
            if leaf not in {'.', 'control'}:
                after[prefix + '.' + leaf] = record
        state_after[prefix + '.list'] = ''.join('/' + path + '\n' for path in sorted(payload)).encode()
    after.update({path: packages.file_record(raw) for path, raw in state_after.items()})
    report = packages.build_report(before, after, blobs, state_before, state_after)
    return {'blobs': blobs, 'before': before, 'after': after, 'state_before': state_before,
            'state_after': state_after, 'report': report}


class PackageDeltaTests(unittest.TestCase):
    def setUp(self):
        self.fixture = synthetic_package_fixture()

    def validate(self):
        f = self.fixture
        return packages.validate_report(f['report'], f['before'], f['after'], f['blobs'])

    def replace_state(self, path, raw, side='after'):
        f = self.fixture
        record = packages.file_record(raw)
        f[side][path] = record
        f['state_' + side][path] = raw
        f['report']['state_files'][path][side] = packages.pack_state(raw)
        f['report']['changes'][path][side] = record

    def test_synthetic_archives_and_receipt_pass_without_host_or_cache_inputs(self):
        self.assertEqual(self.validate(), set(self.fixture['report']['changes']))
        self.assertEqual(packages.sha(POSTINST), packages.POSTINST_SHA)
        self.assertEqual(len(packages.reviewed_packages(self.fixture['blobs'])), 2)

    def test_optional_parent_is_copied_and_unrelated_files_preserved(self):
        parent = {'etc/preserved': packages.file_record(b'preserved')}
        original = copy.deepcopy(parent)
        fixture = synthetic_package_fixture(parent)
        self.assertEqual(parent, original)
        self.assertEqual(fixture['before']['etc/preserved'], fixture['after']['etc/preserved'])

    def test_archive_corruption_cannot_be_admitted_by_receipt(self):
        name = next(name for name in self.fixture['blobs'] if name.startswith('packages/'))
        self.fixture['blobs'][name] += b'corrupt'
        with self.assertRaises(packages.PackageError): self.validate()

    def test_traversal_and_external_symlink_payloads_are_refused(self):
        for entries in ({'../escape': ('file', b'x', 0o644)}, {'link': ('symlink', '/etc/shadow', 0o777)}):
            with self.subTest(entries=entries), self.assertRaises(packages.PackageError):
                packages.tar_members(_tar(entries))

    def test_duplicate_ar_member_is_refused(self):
        with self.assertRaises(packages.PackageError):
            packages.ar_members(_ar([('debian-binary', b'2.0\n'), ('debian-binary', b'2.0\n')]))

    def test_existing_dependency_or_new_unrelated_package_change_is_rejected(self):
        original = copy.deepcopy(self.fixture)
        for raw in (self.fixture['state_after'][packages.STATUS].replace(b'Package: libc6', b'Package: evil-libc'),
                    self.fixture['state_after'][packages.STATUS] + _status([{'Package': 'unrequested', 'Architecture': 'arm64', 'Version': '1', 'Status': 'install ok installed'}])):
            self.fixture = copy.deepcopy(original)
            self.replace_state(packages.STATUS, raw)
            with self.assertRaises(packages.PackageError): self.validate()

    def test_not_configured_package_cannot_pass(self):
        raw = self.fixture['state_after'][packages.STATUS].replace(b'Status: install ok installed', b'Status: install ok unpacked')
        self.replace_state(packages.STATUS, raw)
        with self.assertRaises(packages.PackageError): self.validate()

    def test_pending_triggers_and_nonempty_audit_cannot_be_claimed_clean(self):
        original = copy.deepcopy(self.fixture)
        for field in (b'Triggers-Pending', b'Triggers-Awaited'):
            self.fixture = copy.deepcopy(original)
            raw = self.fixture['state_after'][packages.STATUS].replace(
                b'Package: i2c-tools\n', b'Package: i2c-tools\n' + field + b': man-db\n')
            self.replace_state(packages.STATUS, raw)
            with self.subTest(field=field), self.assertRaises(packages.PackageError): self.validate()
        self.fixture = copy.deepcopy(original)
        self.fixture['report']['checks']['dpkg_audit_clean'] = False
        with self.assertRaises(packages.PackageError): self.validate()

    def test_changed_dependency_version_in_both_states_still_fails_reviewed_pin(self):
        for side in ('before', 'after'):
            raw = self.fixture['state_' + side][packages.STATUS].replace(b'Version: 3.152', b'Version: 3.999')
            self.replace_state(packages.STATUS, raw, side)
        with self.assertRaisesRegex(packages.PackageError, 'dependency'): self.validate()

    def test_forged_payload_or_dpkg_info_bytes_fail_even_when_receipt_matches_child(self):
        original = copy.deepcopy(self.fixture)
        for path in ('usr/sbin/i2cdetect', 'var/lib/dpkg/info/i2c-tools.postinst'):
            self.fixture = copy.deepcopy(original)
            forged = packages.file_record(b'malicious executable', '0755')
            self.fixture['after'][path] = forged
            self.fixture['report']['changes'][path]['after'] = forged
            with self.assertRaises(packages.PackageError): self.validate()

    def test_missing_expected_change_or_unrelated_account_change_cannot_be_claimed(self):
        del self.fixture['report']['changes']['usr/sbin/i2cdetect']
        with self.assertRaises(packages.PackageError): self.validate()
        self.fixture = synthetic_package_fixture()
        self.fixture['after']['etc/passwd'] = packages.file_record(b'unrequested account')
        f = self.fixture
        with self.assertRaises(packages.PackageError):
            packages.build_report(f['before'], f['after'], f['blobs'], f['state_before'], f['state_after'])

    def test_new_or_replaced_ldconfig_entry_is_refused(self):
        original = copy.deepcopy(self.fixture)
        for entries in ([(0xa03, 'libc.so.6', '/evil/libc.so.6'), (0xa03, 'libi2c.so.0', '/lib/aarch64-linux-gnu/libi2c.so.0')],
                        [(0xa03, 'libc.so.6', '/lib/aarch64-linux-gnu/libc.so.6'), (0xa03, 'libi2c.so.0', '/lib/aarch64-linux-gnu/libi2c.so.0'), (0xa03, 'libevil.so', '/evil')]):
            self.fixture = copy.deepcopy(original)
            self.replace_state(packages.CACHE, synthetic_cache(entries))
            with self.assertRaisesRegex(packages.PackageError, 'ldconfig'): self.validate()

    def test_dpkg_file_list_cannot_include_unrequested_path(self):
        path = 'var/lib/dpkg/info/i2c-tools.list'
        self.replace_state(path, self.fixture['state_after'][path] + b'/etc/shadow\n')
        with self.assertRaisesRegex(packages.PackageError, 'file list'): self.validate()

    def test_closed_schema_types_and_checks_are_required(self):
        original = copy.deepcopy(self.fixture)
        for key, value in [('schema_version', True), ('passed', 1), ('extra', 'PRIVATE')]:
            self.fixture = copy.deepcopy(original)
            self.fixture['report'][key] = value
            with self.subTest(key=key), self.assertRaises(packages.PackageError): self.validate()
        self.fixture = copy.deepcopy(original)
        self.fixture['report']['checks']['offline_namespace'] = 1
        with self.assertRaises(packages.PackageError): self.validate()

    def test_boolean_lock_version_rejected_independently(self):
        lock = json.loads(self.fixture['blobs'][packages.LOCK])
        lock['version'] = True
        self.fixture['blobs'][packages.LOCK] = _encoded(lock)
        with self.assertRaises(packages.PackageError):
            packages.reviewed_packages(self.fixture['blobs'])


if __name__ == '__main__':
    unittest.main()
